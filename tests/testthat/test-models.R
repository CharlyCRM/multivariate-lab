testthat::test_that("source schemas and synthetic data work for all cases", {
  for(id in names(case_specs())) {
    case<-load_case(id,tempdir())
    testthat::expect_identical(case$source,"synthetic")
    testthat::expect_equal(case$rows,500)
    fit<-explore_case(case)
    testthat::expect_equal(sum(fit$variance),1,tolerance=1e-8)
    testthat::expect_equal(length(fit$cluster),fit$rows)
  }
})
testthat::test_that("recipes are learned from training, not new observations", {
  train<-data.frame(value=c(1,2,3,NA),group=c("a","b","a",NA))
  r<-fit_recipe(train)
  testthat::expect_equal(r$medians[["value"]],2)
  a<-apply_recipe(data.frame(value=c(NA,10000),group=c("unseen","a")),r)
  testthat::expect_true(all(is.finite(a)))
  testthat::expect_equal(r$medians[["value"]],2)
  testthat::expect_equal(unname(a[1,"value"]),0)
})
testthat::test_that("splits are disjoint, stratified and reproducible", {
  y<-c(rep(0,90),rep(1,10));s<-split_indices(y,TRUE)
  testthat::expect_length(intersect(s$train,s$test),0)
  testthat::expect_equal(sum(y[s$test]),2)
  testthat::expect_identical(s,split_indices(y,TRUE))
  f<-fold_ids(y[s$train],TRUE)
  testthat::expect_equal(length(unique(f)),5)
  testthat::expect_error(split_indices(c(rep(0,20),1),TRUE))
})
testthat::test_that("diagnostic labels and derived targets never leak", {
  blood<-task_data(load_case("blood",tempdir()),"cad")
  testthat::expect_false("classification" %in% names(blood$x))
  student<-task_data(load_case("students",tempdir()),"Mejora")
  testthat::expect_false(any(c("Mejora","Exam_Score") %in% names(student$x)))
})
testthat::test_that("metrics handle perfect and majority-only predictions", {
  m<-classification_metrics(c(0,0,1,1),c(.1,.2,.8,.9))
  testthat::expect_equal(m$f1,1);testthat::expect_equal(m$roc_auc,1)
  testthat::expect_equal(m$average_precision,1)
  majority<-classification_metrics(c(0,0,0,1),rep(.2,4))
  testthat::expect_equal(majority$recall,0)
  testthat::expect_equal(majority$accuracy,.75)
  testthat::expect_equal(classification_metrics(c(0,1),c(.5,.5))$average_precision,.5)
})
testthat::test_that("held-out evaluation and intervals are finite", {
  c<-load_case("students",tempdir())
  regression<-evaluate_task(c,"Exam_Score")
  testthat::expect_equal(regression$test_rows,100)
  testthat::expect_true(is.finite(regression$metrics$rmse))
  testthat::expect_true(all(regression$intervals$lower<=regression$intervals$upper))
  classification<-evaluate_task(c,"Mejora")
  testthat::expect_true(all(classification$observations$prediction>=0 & classification$observations$prediction<=1))
  testthat::expect_length(intersect(classification$split$train,classification$split$test),0)
})
testthat::test_that("exploration rejects too few variables and invalid clusters", {
  case<-load_case("diabetes",tempdir())
